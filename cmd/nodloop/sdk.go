package main

import (
	"encoding/json"
	"fmt"
	"maps"
	"slices"
	"strings"

	"github.com/google/jsonschema-go/jsonschema"
)

// Where go generate writes the record types of each SDK under the sdk folder
const (
	sdkPython     = "python/src/nodloop/records.py"
	sdkTypeScript = "typescript/src/records.ts"
	// The width ruff formats the Python SDK to
	pythonWidth = 140
)

// One kind with the schema its published file holds
type sdkKind struct {
	name, description string
	schema            *jsonschema.Schema
}

// The kinds in the order of the index
type sdkKinds []sdkKind

// The record types of both SDKs from the schema of the newest version of every kind
// The published files are written from the same schemas so the SDK types never drift from schema/
func (kt kindTable) sdk() (map[string][]byte, error) {
	kinds := make(sdkKinds, 0, len(kt))
	for _, k := range kt {
		s, err := k.schema()
		if err != nil {
			return nil, err
		}
		kinds = append(kinds, sdkKind{name: k.name, description: k.description, schema: s})
	}
	return map[string][]byte{sdkTypeScript: kinds.typeScript(), sdkPython: kinds.python()}, nil
}

// The names of the properties of an object in the order of its schema and then by name
func propertyNames(s *jsonschema.Schema) []string {
	out := slices.DeleteFunc(slices.Clone(s.PropertyOrder), func(n string) bool { _, ok := s.Properties[n]; return !ok })
	for _, n := range slices.Sorted(maps.Keys(s.Properties)) {
		if !slices.Contains(out, n) {
			out = append(out, n)
		}
	}
	return out
}

// The JSON types a schema allows besides null and whether it allows null
func jsonTypes(s *jsonschema.Schema) ([]string, bool) {
	types := s.Types
	if s.Type != "" {
		types = []string{s.Type}
	}
	return slices.DeleteFunc(slices.Clone(types), func(t string) bool { return t == "null" }), slices.Contains(types, "null")
}

// The literals of a const or an enum as JSON text
func literals(s *jsonschema.Schema) []string {
	values := s.Enum
	if s.Const != nil {
		values = []any{*s.Const}
	}
	out := make([]string, 0, len(values))
	for _, v := range values {
		// A const or an enum of a published file always encodes
		b, _ := json.Marshal(v)
		out = append(out, string(b))
	}
	return out
}

// The upper camel case of a snake case name such as run or schema_version
func pascal(name string) string {
	var b strings.Builder
	for part := range strings.SplitSeq(name, "_") {
		if part != "" {
			b.WriteString(strings.ToUpper(part[:1]) + part[1:])
		}
	}
	return b.String()
}

func (kinds sdkKinds) typeScript() []byte {
	var b strings.Builder
	b.WriteString("// The records of every kind in their published schemas\n")
	b.WriteString("// Generated by go generate ./cmd/nodloop from the schemas schema/ holds. Do not edit\n")
	for _, k := range kinds {
		fmt.Fprintf(&b, "\n/** %s */\nexport interface %sRecord %s\n", k.description, pascal(k.name), tsObject(k.schema, ""))
	}
	b.WriteString("\n/** Every record kind with the type of its records */\nexport interface Records {\n")
	for _, k := range kinds {
		fmt.Fprintf(&b, "  %s: %sRecord;\n", k.name, pascal(k.name))
	}
	b.WriteString("}\n\n/** A kind of the published index */\nexport type RecordKind = keyof Records;\n")
	b.WriteString("\n/** A record of any kind */\nexport type AnyRecord = Records[RecordKind];\n")
	return []byte(b.String())
}

// The TypeScript type of a schema at the indent of the line it starts on
func tsType(s *jsonschema.Schema, indent string) string {
	if s == nil {
		return "unknown"
	}
	if lits := literals(s); len(lits) > 0 {
		return strings.Join(lits, " | ")
	}
	types, nullable := jsonTypes(s)
	var parts []string
	for _, t := range types {
		switch t {
		case "string":
			parts = append(parts, "string")
		case "integer", "number":
			parts = append(parts, "number")
		case "boolean":
			parts = append(parts, "boolean")
		case "array":
			item := tsType(s.Items, indent)
			// An object alone needs no parentheses though its fields may hold unions
			object := strings.HasPrefix(item, "{") && strings.HasSuffix(item, "}")
			if !object && strings.Contains(item, " | ") {
				item = "(" + item + ")"
			}
			parts = append(parts, item+"[]")
		case "object":
			parts = append(parts, tsObject(s, indent))
		}
	}
	if len(parts) == 0 {
		return "unknown"
	}
	if nullable {
		parts = append(parts, "null")
	}
	return strings.Join(parts, " | ")
}

// An object of named fields one per line
// A map of its values when it names none and any object when it says nothing of its values
func tsObject(s *jsonschema.Schema, indent string) string {
	if len(s.Properties) == 0 {
		if s.AdditionalProperties != nil {
			return "Record<string, " + tsType(s.AdditionalProperties, indent) + ">"
		}
		return "Record<string, unknown>"
	}
	var b strings.Builder
	b.WriteString("{\n")
	for _, name := range propertyNames(s) {
		optional := "?"
		if slices.Contains(s.Required, name) {
			optional = ""
		}
		fmt.Fprintf(&b, "%s  %s%s: %s;\n", indent, name, optional, tsType(s.Properties[name], indent+"  "))
	}
	b.WriteString(indent + "}")
	return b.String()
}

// Words Python reserves that a class body cannot take as a field name
var pythonKeywords = []string{
	"False", "None", "True", "and", "as", "assert", "async", "await", "break", "class", "continue", "def", "del", "elif", "else", "except",
	"finally", "for", "from", "global", "if", "import", "in", "is", "lambda", "nonlocal", "not", "or", "pass", "raise", "return", "try", "while",
	"with", "yield",
}

// One field of a TypedDict
type pyField struct {
	name, typ string
}

// The fields of one part of a TypedDict
type pyFields []pyField

// One TypedDict
type pyClass struct {
	name, doc          string
	required, optional pyFields
}

// The TypedDicts of the objects of every kind in the order Python defines them
// Each comes after the classes its fields name
type pyClasses []pyClass

func (kinds sdkKinds) python() []byte {
	var classes pyClasses
	for _, k := range kinds {
		classes.object(k.schema, pascal(k.name)+"Record", k.description)
	}
	var b strings.Builder
	b.WriteString(`"""The records of every kind in their published schemas` + "\n\nGenerated by go generate ./cmd/nodloop from the schemas schema/ holds. Do not edit\n" + `"""` + "\n\n")
	b.WriteString("from typing import Any, Literal, TypedDict\n")
	for _, c := range classes {
		b.WriteString("\n\n" + c.render())
	}
	b.WriteString("\n\n# A kind of the published index\nRecordKind = Literal[\n")
	for _, k := range kinds {
		fmt.Fprintf(&b, "    %q,\n", k.name)
	}
	b.WriteString("]\n\n# A record of any kind\nAnyRecord = (\n")
	for i, k := range kinds {
		sep := "| "
		if i == 0 {
			sep = ""
		}
		fmt.Fprintf(&b, "    %s%sRecord\n", sep, pascal(k.name))
	}
	b.WriteString(")\n")
	return []byte(b.String())
}

// The Python type of a schema whose object of named fields becomes the class of the name
func (cs *pyClasses) typ(s *jsonschema.Schema, name string) string {
	if s == nil {
		return "Any"
	}
	if lits := literals(s); len(lits) > 0 {
		return "Literal[" + strings.Join(lits, ", ") + "]"
	}
	types, nullable := jsonTypes(s)
	var parts []string
	for _, t := range types {
		switch t {
		case "string":
			parts = append(parts, "str")
		case "integer":
			parts = append(parts, "int")
		case "number":
			parts = append(parts, "float")
		case "boolean":
			parts = append(parts, "bool")
		case "array":
			parts = append(parts, "list["+cs.typ(s.Items, name)+"]")
		case "object":
			parts = append(parts, cs.object(s, name, ""))
		}
	}
	if len(parts) == 0 {
		return "Any"
	}
	if nullable {
		parts = append(parts, "None")
	}
	return strings.Join(parts, " | ")
}

// The class of an object of named fields after the classes of its fields
// A dict of its values when it names none and any dict when it says nothing of its values
func (cs *pyClasses) object(s *jsonschema.Schema, name, doc string) string {
	if len(s.Properties) == 0 {
		if s.AdditionalProperties != nil {
			return "dict[str, " + cs.typ(s.AdditionalProperties, name+"Value") + "]"
		}
		return "dict[str, Any]"
	}
	c := pyClass{name: name, doc: doc}
	for _, field := range propertyNames(s) {
		f := pyField{name: field, typ: cs.typ(s.Properties[field], name+pascal(field))}
		if slices.Contains(s.Required, field) {
			c.required = append(c.required, f)
		} else {
			c.optional = append(c.optional, f)
		}
	}
	*cs = append(*cs, c)
	return name
}

// The class as Python defines it
// 1. a class of required fields alone or of optional fields alone is one TypedDict
// 2. a class of both is its optional fields over a base of its required ones since Python 3.10 has no NotRequired
// 3. a part with a field Python reserves such as from is a TypedDict call since a class body cannot name it
func (c pyClass) render() string {
	switch {
	case len(c.optional) == 0:
		return c.required.part(c.name, c.doc, "TypedDict", false)
	case len(c.required) == 0:
		return c.optional.part(c.name, c.doc, "TypedDict", true)
	case !c.required.reserves() && !c.optional.reserves():
		return c.required.part("_"+c.name+"Required", "", "TypedDict", false) + "\n\n" + c.optional.part(c.name, c.doc, "_"+c.name+"Required", true)
	}
	required, optional := "_"+c.name+"Required", "_"+c.name+"Optional"
	body := "    pass\n"
	if c.doc != "" {
		body = `    """` + c.doc + `"""` + "\n"
	}
	return c.required.part(required, "", "TypedDict", false) + "\n\n" + c.optional.part(optional, "", "TypedDict", true) +
		"\n\n" + "class " + c.name + "(" + required + ", " + optional + "):\n" + body
}

// Whether a field name is a word Python reserves
func (fields pyFields) reserves() bool {
	return slices.ContainsFunc(fields, func(f pyField) bool { return slices.Contains(pythonKeywords, f.name) })
}

// One TypedDict of the fields over the base
// A class unless a field name is reserved and then a TypedDict call
func (fields pyFields) part(name, doc, base string, optional bool) string {
	var b strings.Builder
	total := ""
	if optional {
		total = ", total=False"
	}
	if fields.reserves() {
		fmt.Fprintf(&b, "%s = TypedDict(\n    %q,\n    {\n", name, name)
		for _, f := range fields {
			fmt.Fprintf(&b, "        %q: %s,\n", f.name, f.typ)
		}
		b.WriteString("    },\n")
		if optional {
			b.WriteString("    total=False,\n")
		}
		b.WriteString(")\n")
		return b.String()
	}
	fmt.Fprintf(&b, "class %s(%s%s):\n", name, base, total)
	if doc != "" {
		b.WriteString(`    """` + doc + `"""` + "\n\n")
	}
	for _, f := range fields {
		b.WriteString(pyLine(f))
	}
	return b.String()
}

// One field line within the width ruff formats to
// A Literal too long for it goes one value per line
func pyLine(f pyField) string {
	line := "    " + f.name + ": " + f.typ + "\n"
	values, ok := strings.CutPrefix(f.typ, "Literal[")
	if len(line) <= pythonWidth+1 || !ok || !strings.HasSuffix(values, "]") {
		return line
	}
	var b strings.Builder
	b.WriteString("    " + f.name + ": Literal[\n")
	for v := range strings.SplitSeq(strings.TrimSuffix(values, "]"), ", ") {
		b.WriteString("        " + v + ",\n")
	}
	b.WriteString("    ]\n")
	return b.String()
}
